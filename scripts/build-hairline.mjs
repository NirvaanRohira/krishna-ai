#!/usr/bin/env node
/**
 * Bundles a Hairline figure for the app: the vendored kernel (lib/hairline/kernel.js,
 * MIT, © Lucas Marques) + a small mount shim + the figure, wrapped in one closure, into
 * public/hairline/<name>.js. Run after editing a figure:  node scripts/build-hairline.mjs diyas
 * Check a figure's look with the skill's look.mjs before shipping it (see docs/DESIGN.md).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const name = process.argv[2] || 'diyas'
const kernel = readFileSync('lib/hairline/kernel.js', 'utf8')
const figure = readFileSync(`lib/hairline/${name}.js`, 'utf8')

const shim = `
  var __figures = {};
  function hairline(spec) { __figures[spec.name] = spec; }
  /* Mounts a figure into el, the way @lucasmarkes/hairline's create() does: styles, an
     aria-hidden 400x320 svg, a read-out, and (when play is on) the figure's tour, which the
     kernel pauses for a real pointer and skips under prefers-reduced-motion. */
  function __mountFigure(id, el, opts) {
    opts = opts || {};
    var spec = __figures[id];
    if (!spec || !el) return function () {};
    HL.inject(document);
    el.setAttribute('data-hairline', id);
    var svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('viewBox', '0 0 400 320');
    svg.setAttribute('aria-hidden', 'true');
    el.appendChild(svg);
    var last = null;
    var read = {
      get textContent() { return last; },
      set textContent(v) { if (v !== last) { last = v; if (opts.onRead) opts.onRead(v); } },
    };
    var value = typeof opts.intensity === 'number' ? spec.range[0] + (spec.range[2] - spec.range[0]) * opts.intensity : spec.range[1];
    var played = opts.play && spec.tour ? HL.tour(el, spec.tour) : null;
    var fig = spec.mount({ stage: el, svg: svg, read: read }, value);
    return function destroy() {
      if (played) played.stop();
      fig.destroy();
      svg.remove();
      el.removeAttribute('data-hairline');
    };
  }
`

const out = `/* Hairline figure "${name}" for Kanha. Kernel: @lucasmarkes/hairline, MIT License,
   Copyright (c) 2026 Lucas Marques — see lib/hairline/LICENSE. Generated by
   scripts/build-hairline.mjs; edit lib/hairline/${name}.js, not this file. */
(function () {
${kernel}
${shim}
  /* the figure in its own scope, so its declarations (mount, …) cannot shadow the shim's */
  (function () {
${figure}
  })();
  var prev = window.__hairline && window.__hairline.mount;
  window.__hairline = {
    mount: function (id, el, opts) {
      if (__figures[id]) return __mountFigure(id, el, opts);
      return prev ? prev(id, el, opts) : function () {};
    },
  };
})();
`
mkdirSync('public/hairline', { recursive: true })
writeFileSync(`public/hairline/${name}.js`, out)
console.log(`public/hairline/${name}.js (${(out.length / 1024).toFixed(1)} KB)`)
