'use client'
import { useState } from 'react'
import { useRouter } from 'next/navigation'
import Link from 'next/link'
import { Mark } from '@/components/Mark'

export default function OnboardingPage() {
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)
  // Each consent is a separate, unticked box (DPDP: consent must be specific and
  // affirmative — no pre-ticked or bundled consent). Marketing is optional.
  const [age, setAge] = useState(false)
  const [legal, setLegal] = useState(false)
  const [ai, setAi] = useState(false)
  const [marketing, setMarketing] = useState(false)
  const canContinue = age && legal && ai
  const router = useRouter()

  async function completeOnboarding(): Promise<boolean> {
    try {
      const res = await Promise.race([
        fetch('/api/onboarding/complete', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            ageConfirmed18: age, acceptTerms: legal, acceptPrivacy: legal, aiDisclosure: ai, marketingOptIn: marketing,
          }),
        }),
        new Promise<Response>((_, reject) => setTimeout(() => reject(new Error('timeout')), 5000)),
      ])
      return (res as Response).ok
    } catch {
      return false
    }
  }

  async function handleAccept() {
    setLoading(true)
    setError(null)
    // The profile's onboarding flag is set server-side here; if it fails, the middleware
    // will bounce the user back to /onboarding forever. So verify success (with one retry)
    // instead of pushing to /chat regardless, which created a silent redirect loop.
    let ok = await completeOnboarding()
    if (!ok) ok = await completeOnboarding()
    if (!ok) {
      setError('Something went wrong saving your preferences. Please try again.')
      setLoading(false)
      return
    }
    router.push('/chat')
  }

  return (
    <main className="onboarding-page">
      <div className="fade-up" style={{ width: '100%', display: 'flex', flexDirection: 'column', alignItems: 'center', gap: '0' }}>

        <Mark className="onboarding-mark" />

        <h1 className="onboarding-title">Before you begin</h1>

        <div className="onboarding-body">
          <p>
            <strong>This is an AI, not God and not Krishna.</strong> The figure you see is an
            artistic, AI-animated depiction of Krishna. The guidance is generated by software
            that draws on the Bhagavad Gita, Upanishads, Yoga Sutras and Srimad Bhagavatam — it
            is not divine revelation, and it is not a guru.
          </p>
          <p>
            Use it to reflect, not to replace professional help.
            If you are in crisis, please reach out to{' '}
            <strong>iCall: 9152987821</strong>.
          </p>
          <p>
            The wisdom here is offered with humility.
            Take what serves you, leave what does not.
          </p>
        </div>

        <fieldset className="onboarding-consents">
          <legend className="sr-only">Consent</legend>
          <label><input type="checkbox" checked={age} onChange={(e) => setAge(e.target.checked)} /> <span>I am 18 years of age or older.</span></label>
          <label><input type="checkbox" checked={legal} onChange={(e) => setLegal(e.target.checked)} /> <span>I agree to the <Link href="/terms" target="_blank">Terms</Link> and the <Link href="/privacy" target="_blank">Privacy Notice</Link>, including storing my conversations to personalise guidance.</span></label>
          <label><input type="checkbox" checked={ai} onChange={(e) => setAi(e.target.checked)} /> <span>I understand this is an AI, not God or Krishna, and not a substitute for medical, legal, financial or mental-health care.</span></label>
          <label className="onboarding-optional"><input type="checkbox" checked={marketing} onChange={(e) => setMarketing(e.target.checked)} /> <span>(Optional) Send me occasional updates. You can unsubscribe any time.</span></label>
        </fieldset>

        <button
          onClick={handleAccept}
          disabled={loading || !canContinue}
          className="btn-primary"
        >
          {loading ? 'Entering…' : 'I understand — begin'}
        </button>

        {error && (
          <p role="alert" className="auth-error" style={{ marginTop: '0.75rem' }}>
            {error}
          </p>
        )}
      </div>
    </main>
  )
}
